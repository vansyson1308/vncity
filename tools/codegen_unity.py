"""Generate the Unity (C#) content types from game/schemas, the twin of tools/codegen_ue.py.

Unity reads game/content/**.json as-is (copied to StreamingAssets by the editor setup), so there is
no data conversion step: only typed classes that Newtonsoft.Json fills straight from the content
files. The schema walk is shared with the UE generator (codegen_ue.Model), so both engines see the
same struct/enum names and the same field renames; only the target language differs.

Output: unity/Packages/com.vncity.hanoicity/Runtime/Core/Generated/HanoiContentTypes.cs. The file
is committed; regenerate whenever a schema changes (CI fails while it is stale, and
unity/dotnet tests deserialize every content file into these classes with unknown keys as errors).

Mapping rules (also documented in docs/13-tich-hop-unity.md):
  struct F<Name> -> sealed partial class <Name> (the F prefix dropped: HanoiMissionRow), enum
  E<Name> -> enum <Name> with Unset = 0 and [EnumMember(Value = original)];
  $defs/id, string -> string; integer -> int; money_vnd -> long; number -> double; boolean -> bool;
  a scalar that is not `required` is nullable (int?, long?, double?, bool?) so "absent" stays
  distinguishable (random_events spawn.on_vehicle: absent = either);
  array -> List<T>, map -> Dictionary<string, T> (both default to empty, never null);
  nested object -> class, defaulting to an empty instance (an absent `requires` = always true);
  text -> HanoiText, geo -> HanoiGeo, ref -> HanoiRef, hour_range -> HanoiHourRange,
  oneOf geo|ref -> HanoiTarget, oneOf id|{key: id} -> HanoiNext (all hand-written in
  Runtime/Core/HanoiCoreTypes.cs, null when absent); free-form objects and nested containers ->
  JToken. Property names follow codegen_ue (name -> DisplayName, class -> ClassKind) but
  booleans drop UE's b prefix.

Usage:
  python tools/codegen_unity.py            # write the C# file
  python tools/codegen_unity.py --check    # exit 1 if the committed file is stale
"""

import argparse
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import codegen_ue as ue  # noqa: E402  (shared schema model)

ROOT = ue.ROOT
OUT_PATH = (ROOT / "unity" / "Packages" / "com.vncity.hanoicity" / "Runtime" / "Core" / "Generated"
            / "HanoiContentTypes.cs")
NAMESPACE = "HanoiCity.Content"

CORE_TYPES = {"FHanoiText": "HanoiText", "FHanoiGeo": "HanoiGeo", "FHanoiRef": "HanoiRef",
              "FHanoiHourRange": "HanoiHourRange", "FHanoiTarget": "HanoiTarget",
              "FHanoiNext": "HanoiNext"}
SCALARS = {"name": "string", "string": "string", "int": "int", "int64": "long", "float": "double",
           "double": "double", "bool": "bool", "json": "JToken"}
VALUE_SCALARS = {"int", "int64", "float", "double", "bool"}
# C# keywords cannot appear: identifiers are PascalCase and every C# keyword is lower case.


def cs_name(cpp_name):
    """FHanoiMissionRow -> HanoiMissionRow, EHanoiWeather -> HanoiWeather."""
    if cpp_name in CORE_TYPES:
        return CORE_TYPES[cpp_name]
    if cpp_name[:1] in ("F", "E") and cpp_name[1:2].isupper():
        return cpp_name[1:]
    return cpp_name


def member_name(field):
    n = field["cpp"]
    if field["spec"]["k"] == "bool" and n.startswith("b") and n[1:2].isupper():
        n = n[1:]
    return n


def cs_type(spec, required=True):
    k = spec["k"]
    if spec.get("core") == "optional_bool":
        return "bool?"  # UE's EHanoiOptionalBool; C# has nullable bool
    if k in SCALARS:
        t = SCALARS[k]
        return t + "?" if (k in VALUE_SCALARS and not required) else t
    if k in ("struct", "enum"):
        return cs_name(spec["name"])
    if k == "array":
        return f"List<{cs_type(spec['elem'])}>"
    if k == "map":
        return f"Dictionary<string, {cs_type(spec['value'])}>"
    raise ValueError(k)


def cs_default(spec):
    k = spec["k"]
    if spec.get("core") == "optional_bool":
        return ""
    if k in ("array", "map"):
        return f" = new {cs_type(spec)}();"
    if k == "struct" and "core" not in spec:
        return f" = new {cs_name(spec['name'])}();"
    if k == "enum":
        return f" = {cs_name(spec['name'])}.Unset;"
    return ""


def xml(text):
    text = " ".join(str(text).split())
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def cs_string(s):
    return str(s).replace("\\", "\\\\").replace('"', '\\"')


def summary(text, indent):
    text = xml(text)
    return f"{indent}/// <summary>{text}</summary>\n" if text else ""


def render(model):
    o = ["// GENERATED by tools/codegen_unity.py from game/schemas/*.schema.json. DO NOT EDIT.\n"
         "// Regenerate: python tools/codegen_unity.py\n"
         "// Language level: C# 9 / .NET Standard 2.1 (Unity 6).\n\n"
         "using System;\n"
         "using System.Collections.Generic;\n"
         "using System.Runtime.Serialization;\n"
         "using Newtonsoft.Json;\n"
         "using Newtonsoft.Json.Converters;\n"
         "using Newtonsoft.Json.Linq;\n\n"
         f"namespace {NAMESPACE}\n{{\n"]
    for name in sorted(model.enums):
        cs = cs_name(name)
        o.append("    [JsonConverter(typeof(StringEnumConverter))]\n")
        o.append(f"    public enum {cs}\n    {{\n")
        o.append("        Unset = 0,\n")
        for v in model.enums[name]:
            ident = ue.enum_ident(v)
            if ident == cs:
                raise ValueError(f"{cs}.{ident}: an enum member cannot share the enum's name")
            o.append(f"        [EnumMember(Value = \"{cs_string(v)}\")] {ident},\n")
        o.append("    }\n\n")
    for name in model.order:
        s = model.structs[name]
        cs = cs_name(name)
        doc = s["doc"]
        if s["row"]:
            doc = f"Row of collection '{s['collection']}' (id unique in the collection). {doc}"
        o.append(summary(doc, "    "))
        iface = " : IHanoiRow" if s["row"] else ""
        o.append(f"    [Serializable]\n    public sealed partial class {cs}{iface}\n    {{\n")
        seen = set()
        for f in s["fields"]:
            m = member_name(f)
            if m == cs:
                raise ValueError(f"{cs}.{m}: a member cannot share its class name")
            if m in seen:
                raise ValueError(f"{cs}: two properties map to {m}")
            seen.add(m)
            note = f"json: {f['json']}{' (required)' if f['required'] else ''}"
            doc = f"{f['doc']} [{note}]" if f["doc"] else f"[{note}]"
            o.append(summary(doc, "        "))
            req = ", Required = Required.Always" if f["required"] else ""
            o.append(f"        [JsonProperty(\"{cs_string(f['json'])}\"{req})]\n")
            o.append(f"        public {cs_type(f['spec'], f['required'])} {m} {{ get; set; }}"
                     f"{cs_default(f['spec'])}\n")
        o.append("    }\n\n")
    o.append("    /// <summary>Content collection name -> row class, for the loader.</summary>\n")
    o.append("    public static partial class HanoiCollections\n    {\n")
    o.append("        public static readonly IReadOnlyDictionary<string, Type> RowTypes = "
             "new Dictionary<string, Type>\n        {\n")
    for col in sorted(model.collections):
        o.append(f"            {{ \"{col}\", typeof({cs_name(model.collections[col])}) }},\n")
    o.append("        };\n    }\n}\n")
    return "".join(o)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--schemas", default=str(ue.SCHEMA_DIR))
    ap.add_argument("--out", default=str(OUT_PATH))
    ap.add_argument("--check", action="store_true", help="fail if the committed file is stale")
    a = ap.parse_args(argv)
    model = ue.build_model(a.schemas)
    text = render(model)
    out = pathlib.Path(a.out)
    if a.check:
        if not out.exists() or out.read_text(encoding="utf-8") != text:
            print(f"{out} is stale; run python tools/codegen_unity.py", file=sys.stderr)
            return 1
        print("C# content types up to date")
        return 0
    out.parent.mkdir(parents=True, exist_ok=True)
    if not out.exists() or out.read_text(encoding="utf-8") != text:
        out.write_text(text, encoding="utf-8", newline="\n")
    print(f"C#: {out} ({len(model.order)} classes, {len(model.enums)} enums)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
