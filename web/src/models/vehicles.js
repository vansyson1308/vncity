// Xe cộ dựng thủ tục bằng G: xe số, xe ga, xích lô, ô tô, xe buýt. Trục: x hướng tới trước, y lên, z sang phải.
// Phần vỏ nhựa có mặt nạ đổi màu (color(..., 1)) để mỗi xe trong dòng xe một màu mà vẫn chung một lưới.

function wheel(g, x, r, w, seg = 10) {
  g.push().move(x, r, 0).rotX(Math.PI / 2);
  g.rgb(0.02, 0.02, 0.022).gloss(0).cyl(0, -w / 2, 0, r, r, w, seg, true, true);
  g.rgb(0.35, 0.36, 0.38).gloss(0.6).cyl(0, -w / 2 - 0.005, 0, r * 0.55, r * 0.55, w + 0.01, 8, true, true);
  g.gloss(0).pop();
}

// Đùn một hình chiếu cạnh (đa giác trong mặt phẳng dọc xe: [x tới trước, y lên]) sang hai bên ±hw.
function side(g, pts, hw) { g.push().rotX(-Math.PI / 2); g.prism(pts, -hw, hw, true, true); g.pop(); }

// kind: 'wave' xe số (Sóng Alpha, Mơ), 'scooter' xe ga, 'cub' Cúp 82. detail 1: xe của người chơi (bánh tròn hơn, có gương).
export function motorbike(g, kind = 'wave', detail = 1) {
  const sc = kind === 'scooter', cub = kind === 'cub';
  const wr = sc ? 0.24 : 0.29, fx = 0.63, rx = -0.6, seg = detail ? 14 : 7;
  wheel(g, fx, wr, 0.09, seg); wheel(g, rx, wr, 0.1, seg);
  // phuộc trước, cổ lái, tay lái
  g.rgb(0.3, 0.31, 0.33).gloss(0.5);
  g.tube([fx, wr, -0.07], [0.42, 0.92, -0.06], 0.022, 4).tube([fx, wr, 0.07], [0.42, 0.92, 0.06], 0.022, 4);
  g.rgb(0.06, 0.06, 0.07).gloss(0.2).tube([0.4, 1.03, -0.3], [0.4, 1.03, 0.3], 0.018, 4);
  if (detail) {
    g.tube([0.4, 1.03, -0.22], [0.36, 1.2, -0.27], 0.008, 3).tube([0.4, 1.03, 0.22], [0.36, 1.2, 0.27], 0.008, 3);
    g.cube(0.36, 1.18, -0.28, 0.02, 0.07, 0.11).cube(0.36, 1.18, 0.28, 0.02, 0.07, 0.11);
    g.rgb(0.03, 0.03, 0.03).tube([0.4, 1.03, -0.3], [0.4, 1.03, -0.2], 0.024, 5).tube([0.4, 1.03, 0.2], [0.4, 1.03, 0.3], 0.024, 5);
  }
  // đầu xe + đèn pha, chắn bùn trước, yếm
  g.color(0xd8d8d8, 1).gloss(0.7);
  side(g, [[0.33, 0.86], [0.5, 0.83], [0.56, 0.95], [0.5, 1.07], [0.35, 1.06]], 0.13);
  side(g, [[0.4, wr + 0.3], [fx, wr + 0.36], [fx + 0.23, wr + 0.26], [fx + 0.21, wr + 0.22], [fx, wr + 0.31], [0.42, wr + 0.25]], 0.06);
  side(g, [[0.25, 0.3], [0.34, 0.27], [0.47, 0.86], [0.4, 0.88]], sc ? 0.21 : 0.19);
  g.rgb(1, 0.95, 0.8).glow(0.85).quad([0.545, 0.89, 0.085], [0.545, 0.89, -0.085], [0.52, 1.03, -0.085], [0.52, 1.03, 0.085]).glow(0);
  if (sc) {
    g.color(0xd8d8d8, 1);
    side(g, [[-0.96, 0.52], [-0.9, 0.76], [-0.14, 0.74], [-0.04, 0.34], [0.3, 0.3], [0.34, 0.2], [-0.2, 0.18], [-0.74, 0.3]], 0.19);
    g.rgb(0.03, 0.03, 0.035).gloss(0.15); side(g, [[-0.86, 0.76], [-0.84, 0.86], [-0.3, 0.85], [-0.12, 0.8], [-0.14, 0.74]], 0.17);
  } else {
    g.color(0xd8d8d8, 1);
    side(g, [[-0.94, 0.6], [-0.88, 0.75], [-0.15, 0.72], [0.05, 0.6], [0.3, 0.62], [0.36, 0.5], [0.1, 0.38], [-0.3, 0.42], [-0.62, 0.47]], cub ? 0.12 : 0.14);
    g.rgb(0.03, 0.03, 0.035).gloss(0.15); side(g, [[-0.8, 0.75], [-0.78, 0.83], [-0.3, 0.84], [-0.02, 0.78], [0.0, 0.72], [-0.15, 0.72]], 0.14);
    g.rgb(0.2, 0.2, 0.22).gloss(0.4); side(g, [[-0.28, 0.2], [0.14, 0.2], [0.18, 0.36], [-0.3, 0.42]], 0.13);
    if (cub) { g.color(0xe8e8e0, 0); side(g, [[0.1, 0.3], [0.3, 0.3], [0.36, 0.7], [0.14, 0.7]], 0.2); }
  }
  // ống xả, đèn hậu, baga, biển số
  g.rgb(0.45, 0.45, 0.47).gloss(0.8).tube([-0.1, 0.24, 0.17], [-0.86, 0.34, 0.18], 0.045, 6);
  g.rgb(0.9, 0.05, 0.03).glow(0.7).quad([-0.945, 0.61, -0.08], [-0.945, 0.61, 0.08], [-0.9, 0.72, 0.08], [-0.9, 0.72, -0.08]).glow(0);
  g.rgb(0.08, 0.08, 0.09).gloss(0.3).box(-1.02, 0.75, -0.12, -0.8, 0.77, 0.12);
  if (detail) g.rgb(0.8, 0.8, 0.75).gloss(0).quad([-0.97, 0.44, -0.1], [-0.97, 0.44, 0.1], [-0.95, 0.56, 0.1], [-0.95, 0.56, -0.1]);
  g.gloss(0);
  return g;
}

// Ô tô 4 chỗ / 7 chỗ đơn giản. tint: thân xe đổi màu.
export function car(g, suv = false) {
  const L = suv ? 4.5 : 4.3, W = 1.76, H = suv ? 1.66 : 1.45, cl = 0.2;
  for (const x of [L / 2 - 0.85, -L / 2 + 0.85]) for (const z of [-W / 2 + 0.1, W / 2 - 0.1]) { g.push().move(0, 0, z); wheel(g, x, 0.33, 0.2, 10); g.pop(); }
  g.color(0xdcdcdc, 1).gloss(0.8);
  g.box(-L / 2, cl, -W / 2, L / 2, cl + (suv ? 0.72 : 0.6), W / 2);
  const y0 = cl + (suv ? 0.72 : 0.6), y1 = H, a = suv ? 1.9 : 1.25, b = suv ? 0.75 : 0.55, c = 1.0;
  // khoang kính: thang cân
  const top = [[L / 2 - a, y1], [-L / 2 + b + 0.35, y1]], bot = [[L / 2 - c + 0.45, y0], [-L / 2 + b - 0.15, y0]];
  const zs = W / 2 - 0.06, zt = W / 2 - 0.2;
  g.quad([top[1][0], y1, -zt], [top[0][0], y1, -zt], [top[0][0], y1, zt], [top[1][0], y1, zt]); // nóc
  g.rgb(0.03, 0.05, 0.07).gloss(1);
  g.quad([bot[0][0], y0, zs], [bot[0][0], y0, -zs], [top[0][0], y1, -zt], [top[0][0], y1, zt]);   // kính trước
  g.quad([bot[1][0], y0, -zs], [bot[1][0], y0, zs], [top[1][0], y1, zt], [top[1][0], y1, -zt]);   // kính sau
  g.quad([bot[1][0], y0, zs], [bot[0][0], y0, zs], [top[0][0], y1, zt], [top[1][0], y1, zt]);     // kính phải
  g.quad([bot[0][0], y0, -zs], [bot[1][0], y0, -zs], [top[1][0], y1, -zt], [top[0][0], y1, -zt]); // kính trái
  g.rgb(1, 0.96, 0.85).glow(0.8).gloss(0.5);
  for (const z of [-W / 2 + 0.3, W / 2 - 0.3]) g.quad([L / 2 + 0.002, y0 - 0.3, z + 0.22], [L / 2 + 0.002, y0 - 0.3, z - 0.22], [L / 2 + 0.002, y0 - 0.12, z - 0.22], [L / 2 + 0.002, y0 - 0.12, z + 0.22]);
  g.rgb(0.9, 0.04, 0.03).glow(0.7);
  for (const z of [-W / 2 + 0.3, W / 2 - 0.3]) g.quad([-L / 2 - 0.002, y0 - 0.3, z - 0.22], [-L / 2 - 0.002, y0 - 0.3, z + 0.22], [-L / 2 - 0.002, y0 - 0.12, z + 0.22], [-L / 2 - 0.002, y0 - 0.12, z - 0.22]);
  g.glow(0).gloss(0);
  return g;
}

// Xe buýt Hà Nội: thân hộp dài, dải kính, hai màu.
export function bus(g) {
  const L = 10.5, W = 2.45, H = 3.05, cl = 0.32;
  for (const x of [L / 2 - 2.2, -L / 2 + 2.6]) for (const z of [-W / 2 + 0.14, W / 2 - 0.14]) { g.push().move(0, 0, z); wheel(g, x, 0.48, 0.28, 10); g.pop(); }
  g.color(0xf2efe4, 0).gloss(0.5).box(-L / 2, cl, -W / 2, L / 2, H, W / 2);
  g.color(0xd9a520, 0).box(-L / 2 - 0.004, cl, -W / 2 - 0.004, L / 2 + 0.004, cl + 0.75, W / 2 + 0.004, 'xXzZ');
  g.color(0xb3261e, 0).box(-L / 2 - 0.006, cl + 0.75, -W / 2 - 0.006, L / 2 + 0.006, cl + 0.95, W / 2 + 0.006, 'xXzZ');
  g.rgb(0.03, 0.05, 0.07).gloss(1).box(-L / 2 + 0.3, 1.45, -W / 2 - 0.008, L / 2 - 0.3, 2.5, W / 2 + 0.008, 'zZ');
  g.box(L / 2 + 0.008, 1.3, -W / 2 + 0.15, L / 2 + 0.008, 2.6, W / 2 - 0.15, 'X').box(-L / 2 - 0.008, 1.7, -W / 2 + 0.2, -L / 2 - 0.008, 2.5, W / 2 - 0.2, 'x');
  g.quad([L / 2 + 0.009, 1.3, W / 2 - 0.15], [L / 2 + 0.009, 1.3, -W / 2 + 0.15], [L / 2 + 0.009, 2.6, -W / 2 + 0.15], [L / 2 + 0.009, 2.6, W / 2 - 0.15]);
  g.rgb(1, 0.96, 0.85).glow(0.8);
  for (const z of [-W / 2 + 0.35, W / 2 - 0.35]) g.quad([L / 2 + 0.01, 0.7, z + 0.2], [L / 2 + 0.01, 0.7, z - 0.2], [L / 2 + 0.01, 0.9, z - 0.2], [L / 2 + 0.01, 0.9, z + 0.2]);
  g.rgb(0.9, 0.04, 0.03).glow(0.7);
  for (const z of [-W / 2 + 0.35, W / 2 - 0.35]) g.quad([-L / 2 - 0.01, 0.9, z - 0.2], [-L / 2 - 0.01, 0.9, z + 0.2], [-L / 2 - 0.01, 1.1, z + 0.2], [-L / 2 - 0.01, 1.1, z - 0.2]);
  g.glow(0).gloss(0);
  return g;
}

